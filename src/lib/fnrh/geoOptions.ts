/** Países (nome em português, estilo ficha Embratur) para sugestão nos campos FNRH. */

export function normalizeGeoSearch(value: string): string {
  return value
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .toUpperCase()
    .trim();
}

export function filterGeoOptions(
  options: readonly string[],
  query: string,
  limit = 50,
): string[] {
  const q = normalizeGeoSearch(query);
  if (!q) {
    return options.slice(0, limit);
  }
  const starts: string[] = [];
  const includes: string[] = [];
  for (const opt of options) {
    const n = normalizeGeoSearch(opt);
    if (n.startsWith(q)) starts.push(opt);
    else if (n.includes(q)) includes.push(opt);
    if (starts.length + includes.length >= limit * 2) break;
  }
  return [...starts, ...includes].slice(0, limit);
}

